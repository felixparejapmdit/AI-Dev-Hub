// Config generator for different AI IDE platforms
import { WorkspaceCartItem, TargetPlatform, GeneratedConfig, AIModel, MCPServer, Skill } from "@/types";

export function generateConfig(
  items: WorkspaceCartItem[],
  platform: TargetPlatform
): GeneratedConfig {
  const models = items.filter((i) => i.type === "model").map((i) => i.item as AIModel);
  const mcpServers = items.filter((i) => i.type === "mcp").map((i) => i.item as MCPServer);
  const skills = items.filter((i) => i.type === "skill").map((i) => i.item as Skill);

  switch (platform) {
    case "cursor":
      return generateCursorConfig(models, mcpServers, skills);
    case "claude":
      return generateClaudeConfig(models, mcpServers, skills);
    case "antigravity":
    default:
      return generateAntigravityConfig(models, mcpServers, skills);
  }
}

function generateAntigravityConfig(
  models: AIModel[],
  mcpServers: MCPServer[],
  skills: Skill[]
): GeneratedConfig {
  const lines: string[] = [
    "# VibeLaunch — Antigravity Configuration",
    "# Generated by AI Dev Hub · https://vibelaunch.dev",
    `# Generated at: ${new Date().toISOString()}`,
    "",
  ];

  if (models.length > 0) {
    lines.push("## AI Models");
    models.forEach((m) => {
      lines.push(`# ${m.name} (${m.provider}) — ${m.contextWindow.toLocaleString()}k context`);
      if (m.apiSlug) lines.push(`model: ${m.apiSlug}`);
    });
    lines.push("");
  }

  if (mcpServers.length > 0) {
    lines.push("## MCP Servers");
    lines.push("mcp_servers:");
    mcpServers.forEach((s) => {
      lines.push(`  - name: "${s.name}"`);
      lines.push(`    command: "${s.installCommand}"`);
      if (s.description) lines.push(`    # ${s.description}`);
    });
    lines.push("");
  }

  if (skills.length > 0) {
    lines.push("## Skills / System Prompts");
    skills.forEach((sk) => {
      lines.push(`# --- ${sk.title} ---`);
      lines.push(`# Category: ${sk.category}`);
      lines.push(`system_prompt: |`);
      sk.systemPrompt.split("\n").forEach((l) => lines.push(`  ${l}`));
      lines.push("");
    });
  }

  const content = lines.join("\n");
  return { platform: "antigravity", content, filename: "antigravity.config.yaml" };
}

function generateCursorConfig(
  models: AIModel[],
  mcpServers: MCPServer[],
  skills: Skill[]
): GeneratedConfig {
  const lines: string[] = [
    "# VibeLaunch — Cursor Rules",
    "# Generated by AI Dev Hub · https://vibelaunch.dev",
    `# Generated at: ${new Date().toISOString()}`,
    "",
    "# ================================================",
    "# CURSOR AI CONFIGURATION",
    "# ================================================",
    "",
  ];

  if (models.length > 0) {
    lines.push("# Preferred Models");
    models.forEach((m) => {
      lines.push(`# - ${m.name} by ${m.provider} (${m.contextWindow.toLocaleString()} ctx)`);
    });
    lines.push("");
  }

  if (skills.length > 0) {
    lines.push("# System Instructions");
    skills.forEach((sk) => {
      lines.push(`# === ${sk.title.toUpperCase()} ===`);
      lines.push(sk.systemPrompt);
      lines.push("");
    });
  }

  if (mcpServers.length > 0) {
    lines.push("# MCP Server Setup (add to .cursor/mcp.json)");
    lines.push("# {");
    lines.push('#   "mcpServers": {');
    mcpServers.forEach((s, i) => {
      const isLast = i === mcpServers.length - 1;
      lines.push(`#     "${s.name.toLowerCase().replace(/\s+/g, "-")}": {`);
      lines.push(`#       "command": "npx",`);
      lines.push(`#       "args": ["${s.npmPackage ?? s.installCommand}"]`);
      lines.push(`#     }${isLast ? "" : ","}`);
    });
    lines.push('#   }');
    lines.push('# }');
  }

  const content = lines.join("\n");
  return { platform: "cursor", content, filename: ".cursorrules" };
}

function generateClaudeConfig(
  models: AIModel[],
  mcpServers: MCPServer[],
  skills: Skill[]
): GeneratedConfig {
  const lines: string[] = [
    "# VibeLaunch — Claude.ai / Claude Desktop Configuration",
    "# Generated by AI Dev Hub · https://vibelaunch.dev",
    `# Generated at: ${new Date().toISOString()}`,
    "",
  ];

  if (skills.length > 0) {
    lines.push("## Custom System Prompt");
    lines.push("");
    skills.forEach((sk) => {
      lines.push(`### ${sk.title}`);
      lines.push(sk.systemPrompt);
      lines.push("");
    });
  }

  if (mcpServers.length > 0) {
    lines.push("## MCP Servers for Claude Desktop");
    lines.push("Add the following to your claude_desktop_config.json:");
    lines.push("");
    lines.push("```json");
    const mcpJson: Record<string, { command: string; args: string[] }> = {};
    mcpServers.forEach((s) => {
      mcpJson[s.name.toLowerCase().replace(/\s+/g, "_")] = {
        command: "npx",
        args: [s.npmPackage ?? s.installCommand],
      };
    });
    lines.push(JSON.stringify({ mcpServers: mcpJson }, null, 2));
    lines.push("```");
    lines.push("");
  }

  if (models.length > 0) {
    lines.push("## Recommended Models");
    models.forEach((m) => {
      lines.push(`- **${m.name}** (${m.provider}) — Context: ${m.contextWindow.toLocaleString()} tokens`);
      if (m.apiSlug) lines.push(`  - API slug: \`${m.apiSlug}\``);
    });
  }

  const content = lines.join("\n");
  return { platform: "claude", content, filename: "claude_config.md" };
}
